"""Voice adapter and voiceover timing (Phase 9, Agent 11).

Only providers whose voices are cleared for commercial use may be used
(PROJECT_SPEC section 6). The default provider ``mock`` produces a silent test
voice of the right length: it exercises timing, mixing and subtitles without any
cost or rights question. A real provider is added to ``PROVIDERS`` once the
operator has chosen one and approved a budget.

Timing: every script beat has a slot in the clip. The spoken length of a beat is
estimated from its words and the calm speaking pace of the language; if it does
not fit, the voice is sped up by at most ``MAX_TEMPO`` and anything still too long
is reported for the quality check.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import asdict, dataclass
from decimal import Decimal
from pathlib import Path
from typing import Any, Protocol

from core.config import Settings
from core.enums import Language
from services import media
from services.creative import WORDS_PER_SECOND

MOCK = "mock"
MAX_TEMPO = 1.15  # faster than this sounds rushed
MIN_SEGMENT_S = 0.6


class VoiceError(RuntimeError):
    pass


class VoiceProvider(Protocol):
    name: str
    #: Must be True: the provider's terms allow commercial use of the generated audio.
    commercial_use_cleared: bool
    voices: dict[Language, str]
    #: Upper bound per second of speech, asked from the budget service before a call.
    cost_per_second_eur: Decimal

    def synthesize(self, text: str, language: Language, voice_id: str, out: Path) -> float:
        """Write speech for ``text`` to ``out`` (any audio FFmpeg reads); return seconds."""
        ...


class MockVoice:
    """Silent test voice with the length real speech would have."""

    name = MOCK
    commercial_use_cleared = True  # silence generated by us, no third-party rights
    cost_per_second_eur = Decimal("0")

    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        self.voices = {Language.DE: "mock-de", Language.EN: "mock-en"}

    def synthesize(self, text: str, language: Language, voice_id: str, out: Path) -> float:
        seconds = max(MIN_SEGMENT_S, spoken_seconds(text, language))
        media.run(
            [
                self.settings.ffmpeg_bin,
                "-v",
                "error",
                "-y",
                "-f",
                "lavfi",
                "-t",
                f"{seconds:.3f}",
                "-i",
                "anullsrc=r=48000:cl=mono",
                "-c:a",
                "pcm_s16le",
                str(out),
            ],
            timeout=60,
        )
        return seconds


#: Real providers by operator setting ``tts_provider``. Empty until one is approved.
PROVIDERS: dict[str, Callable[[Settings], VoiceProvider]] = {MOCK: MockVoice}


def get_provider(name: str, settings: Settings) -> VoiceProvider | None:
    factory = PROVIDERS.get(name)
    return factory(settings) if factory else None


def spoken_seconds(text: str, language: Language) -> float:
    return len(text.split()) / WORDS_PER_SECOND[language]


@dataclass
class Segment:
    kind: str
    text: str
    start_s: float
    end_s: float  # where the voice actually ends
    slot_end_s: float  # where the beat's slot ends
    tempo: float
    overflow_s: float  # still too long after speeding up

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


def plan_segment(beat: dict[str, Any], natural_s: float, clip_s: float) -> Segment:
    start = float(beat["start_s"])
    slot_end = min(float(beat["end_s"]), clip_s)
    slot = max(0.1, slot_end - start)
    tempo = min(MAX_TEMPO, max(1.0, natural_s / slot))
    spoken = natural_s / tempo
    overflow = max(0.0, spoken - slot)
    return Segment(
        kind=str(beat["kind"]),
        text=str(beat["text"]),
        start_s=round(start, 2),
        end_s=round(min(start + spoken, clip_s), 2),
        slot_end_s=round(slot_end, 2),
        tempo=round(tempo, 3),
        overflow_s=round(overflow, 2),
    )


def mix_command(
    settings: Settings, parts: list[tuple[Path, Segment]], clip_s: float, out: Path
) -> list[str]:
    """One voice track of clip length: every part delayed to its start and sped up."""
    cmd = [settings.ffmpeg_bin, "-v", "error", "-y"]
    for path, _ in parts:
        cmd += ["-i", str(path)]
    chains = []
    for i, (_, seg) in enumerate(parts):
        delay = int(seg.start_s * 1000)
        chains.append(f"[{i}:a]atempo={seg.tempo},adelay={delay}:all=1[v{i}]")
    inputs = "".join(f"[v{i}]" for i in range(len(parts)))
    graph = ";".join(chains) + f";{inputs}amix=inputs={len(parts)}:normalize=0,"
    graph += f"apad,atrim=0:{clip_s:.3f},aformat=sample_rates=48000:channel_layouts=stereo[a]"
    cmd += ["-filter_complex", graph, "-map", "[a]", "-c:a", "aac", "-b:a", "128k", str(out)]
    return cmd
